async original => {
  const context = await original.context().browser().newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
  const page = await context.newPage(), base = new URL(original.url()).origin, errors = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  page.on('pageerror', error => errors.push(error.message));
  let release;
  let phase='fallback';
  const held = new Promise(resolve => { release = resolve; });
  try {
    await page.route('**/vendor/hero/hero-motion.js', async route => { await held; await route.continue().catch(()=>{}); });
    await page.addInitScript(() => {
      window.__heroCLS=0;
      new PerformanceObserver(list => list.getEntries().forEach(entry => { if (!entry.hadRecentInput) window.__heroCLS+=entry.value; })).observe({type:'layout-shift',buffered:true});
      document.addEventListener('DOMContentLoaded',()=>{window.__originalH1=document.getElementById('page-title');window.__originalText=window.__originalH1.textContent;});
      window.__splitObserved=false;
      new MutationObserver(()=>{if(document.querySelector('#page-title .hero-word'))window.__splitObserved=true;}).observe(document,{subtree:true,childList:true});
    });
    await page.goto(base);
    assert(await page.locator('#page-title').isVisible(), 'Delayed bundle hides the fallback heading');
    assert(await page.locator('h1').count()===1, 'Fallback heading duplicated');
    assert(await page.locator('#hero-motion-root').count()===1, 'React island mount is missing');
    await page.evaluate(()=>document.fonts.ready);
    await page.waitForFunction(()=>document.documentElement.dataset.analysisState==='success');
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    const initialCLS=await page.evaluate(()=>{const value=window.__heroCLS;window.__heroCLS=0;return value;});
    const before = await page.locator('#page-title').boundingBox();
    release();
    await page.waitForFunction(()=>document.getElementById('hero-motion-root')?.dataset.heroReady==='true');
    phase='active Motion blur';
    await page.waitForFunction(()=>{
      const el=document.getElementById('hero-description'),blur=parseFloat(getComputedStyle(el).filter.replace('blur(',''));
      return el.getAnimations().length>0 && blur>0 && blur<=4;
    });
    await page.waitForFunction(()=>!document.querySelector('#page-title .hero-word'));
    phase='pointer';
    assert(await page.evaluate(()=>window.__splitObserved),'Sourced SplitText word entrance did not run');
    assert(await page.evaluate(()=>document.getElementById('page-title')===window.__originalH1&&window.__originalH1.textContent===window.__originalText),'Island replaces or changes static headline');
    assert(await page.locator('#hero-motion-root').textContent()==='', 'Effect island owns duplicate text');
    const after = await page.locator('#page-title').boundingBox();
    assert(Math.abs(before.height-after.height)<0.5, 'Island changes heading layout');
    const art=page.locator('#hero-art'),box=await art.boundingBox();
    await page.mouse.move(box.x+box.width*.9,box.y+box.height*.8);
    await page.waitForFunction(()=>[...document.querySelectorAll('[data-hero-drift]')].some(node=>node.style.translate));
    assert(await page.locator('[data-hero-drift]').evaluateAll(nodes=>nodes.every(node=>(node.style.translate.match(/-?[\d.]+/g)||[]).every(n=>Math.abs(Number(n))<=6))), 'Pointer exceeds 6px');
    await page.mouse.move(0,0);
    await page.waitForFunction(()=>[...document.querySelectorAll('[data-hero-drift]')].every(node=>!node.style.translate));
    await page.mouse.move(box.x+box.width*.9,box.y+box.height*.8);
    await page.waitForFunction(()=>[...document.querySelectorAll('[data-hero-drift]')].some(node=>node.style.translate));
    await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
    assert(await page.locator('[data-hero-drift]').evaluateAll(nodes=>nodes.every(node=>!node.style.translate)), 'Blur leaves drift');
    await page.mouse.move(box.x+box.width*.9,box.y+box.height*.8);
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.waitForFunction(()=>document.getElementById('hero-motion-root').dataset.heroState==='reduced');
    assert(await page.locator('[data-hero-drift]').evaluateAll(nodes=>nodes.every(node=>!node.style.translate)), 'Runtime reduce leaves drift');
    assert(await page.evaluate(()=>!document.querySelector('#page-title .hero-word')&&!document.getElementById('hero-description').style.filter), 'Runtime reduce leaves split or blur');
    await page.emulateMedia({reducedMotion:'no-preference'});
    phase='pointer after runtime reduce';
    await page.waitForFunction(()=>document.getElementById('hero-motion-root').dataset.heroState==='active');
    await page.mouse.move(box.x+box.width*.7,box.y+box.height*.7);
    await page.waitForFunction(()=>[...document.querySelectorAll('[data-hero-drift]')].some(node=>node.style.translate));
    await page.evaluate(()=>window.scrollTo(0,document.getElementById('workspace').offsetTop+200));
    await page.waitForFunction(()=>[...document.querySelectorAll('[data-hero-drift]')].every(node=>!node.style.translate));
    await page.locator('#workspace').scrollIntoViewIfNeeded();
    await page.waitForFunction(()=>[...document.querySelectorAll('[data-hero-drift]')].every(node=>!node.style.translate));
    await page.waitForFunction(()=>document.getElementById('workspace').dataset.heroEntered==='true');
    await page.waitForFunction(()=>!document.getElementById('workspace').style.transform);
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.locator('#workspace').scrollIntoViewIfNeeded();
    assert(await page.locator('#workspace').getAttribute('data-hero-entered')==='true','Section entrance does not stay completed');
    await page.emulateMedia({media:'print'});
    assert(await page.locator('[data-hero-drift]').evaluateAll(nodes=>nodes.every(node=>!node.style.translate)), 'Print leaves drift');
    const cls=await page.evaluate(()=>window.__heroCLS);
    assert(cls<0.05, `Layout shifts exceeded budget: ${cls}`);
    assert(errors.length===0, errors.join('; '));
    const fallback=await context.newPage();
    await fallback.route('**/vendor/hero/hero-motion.js', route=>route.abort());
    await fallback.goto(base);
    assert(await fallback.locator('#page-title').isVisible()&&await fallback.locator('h1').count()===1,'Failed island hides or duplicates heading');
    await fallback.close();
    const reduced=await original.context().browser().newContext({reducedMotion:'reduce'});
    const reducedPage=await reduced.newPage();await reducedPage.goto(base);
    await reducedPage.waitForFunction(()=>document.getElementById('hero-motion-root')?.dataset.heroState==='reduced');
    assert(!await reducedPage.locator('#page-title').getAttribute('data-hero-split-started'),'Initial reduced motion animates heading');
    assert(await reducedPage.locator('[data-hero-drift]').evaluateAll(nodes=>nodes.every(node=>!node.style.translate)),'Initial reduce drifts artwork');
    await reduced.close();
    const interrupted=await context.newPage();await interrupted.goto(base);
    await interrupted.waitForFunction(()=>document.querySelector('#page-title .hero-word'));
    await interrupted.emulateMedia({media:'print'});
    await interrupted.waitForFunction(()=>!document.querySelector('#page-title .hero-word'));
    assert(await interrupted.evaluate(()=>!document.getElementById('hero-description').style.filter),'Printing mid-entrance leaves blur');
    await interrupted.close();
    const noObserver=await context.newPage();
    await noObserver.addInitScript(()=>{window.IntersectionObserver=undefined;});
    const fallbackErrors=[];noObserver.on('pageerror',error=>fallbackErrors.push(error.message));
    await noObserver.goto(base);
    await noObserver.waitForFunction(()=>document.getElementById('hero-motion-root')?.dataset.heroState==='fallback');
    assert(await noObserver.locator('#page-title').isVisible()&&fallbackErrors.length===0,'Missing observer breaks progressive enhancement');
    await noObserver.close();
    const noJS=await original.context().browser().newContext({javaScriptEnabled:false});
    const staticPage=await noJS.newPage();await staticPage.goto(base);
    assert(await staticPage.locator('#page-title').isVisible()&&await staticPage.locator('a[href="#workspace"]').first().isVisible(),'No-JS fallback is unavailable');
    await noJS.close();
    return {ok:true,cls,initialCLS,checks:['delay','failed bundle','heading identity/text','no duplicate text','pointer limit/leave/blur/offscreen','initial/runtime reduce','once sections','mid-entrance print','noJS']};
  } catch(error) { throw new Error(`${phase}: ${error.message}`); }
  finally { release(); await context.close(); }
}
