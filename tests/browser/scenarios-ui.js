async original => {
  const context = await original.context().browser().newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), base = new URL(original.url()).origin, errors = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(base);
    await page.waitForFunction(() => document.documentElement.dataset.analysisState === 'success');
    assert(await page.locator('#scenario-save').count() === 1, 'Scenario save control is missing');
    await page.locator('#scenario-save').click();
    await page.locator('#scenario-name').fill('=Исследование <script>');
    await page.locator('#scenario-note').fill('Проверить вход и аренду');
    await page.locator('#scenario-submit').click();
    await page.waitForFunction(() => document.querySelectorAll('[data-testid="scenario-card"]').length === 1);
    assert(await page.locator('#scenario-list script').count() === 0, 'Scenario name inserted as HTML');
    assert(await page.locator('#data-quality [data-testid="data-quality-block"]').count() === 1, 'Current quality block missing');
    assert(await page.locator('#recommendation-list [data-testid="explanation-block"]').count() > 0, 'Recommendation explanations missing');
    await page.reload();
    await page.waitForFunction(() => document.querySelectorAll('[data-testid="scenario-card"]').length === 1);
    await page.getByTestId('scenario-duplicate').click();
    await page.waitForFunction(() => document.querySelectorAll('[data-testid="scenario-card"]').length === 2);
    await page.getByTestId('scenario-edit').first().click();
    await page.locator('#scenario-name').fill('Первое исследование');
    await page.locator('#scenario-submit').click();
    await page.waitForFunction(() => document.querySelector('#scenario-list').textContent.includes('Первое исследование'));
    await page.getByTestId('scenario-compare').first().click();
    assert((await page.locator('#scenario-comparison').innerText()).includes('второй'), 'Single comparison selection has no guidance');
    await page.getByTestId('scenario-compare').nth(1).click();
    assert(await page.locator('#scenario-comparison table').count() === 1, 'Comparison table is missing');
    assert(!/оценка внутри|Относительная оценка/.test(await page.locator('#scenario-comparison table').innerText()), 'Cross-analysis comparison includes score');
    await page.locator('#scenario-comparison').screenshot({ path: 'tests/artifacts/scenarios/ui-comparison.png' });
    await page.getByTestId('scenario-duplicate').last().click();
    await page.waitForFunction(() => document.querySelectorAll('[data-testid="scenario-card"]').length === 3);
    await page.getByTestId('scenario-compare').last().click();
    assert(await page.getByTestId('scenario-compare').last().getAttribute('aria-pressed') === 'false', 'Third scenario entered comparison');
    await page.getByTestId('scenario-delete').last().click();
    await page.locator('#scenario-delete-confirm').click();
    await page.waitForFunction(() => document.querySelectorAll('[data-testid="scenario-card"]').length === 2);
    const download = page.waitForEvent('download');
    await page.locator('#scenario-export').click();
    assert((await download).suggestedFilename().includes('scenarios'), 'Scenario CSV filename is ambiguous');
    await page.evaluate(() => { window.print = () => { window.__scenarioPrinted = true; }; });
    await page.locator('#scenario-print').click();
    assert(await page.evaluate(() => window.__scenarioPrinted && document.querySelector('#print-report-content').textContent.includes('Первое исследование')), 'Scenario print report missing');
    assert(await page.locator('#print-report-content .scenario-print-context').count() === 2, 'Print omitted full scenario contexts');
    await page.emulateMedia({ media: 'print' });
    assert(!await page.locator('#scenarios-section').isVisible(), 'Scenario controls leak into print');
    await page.emulateMedia({ media: null });
    await page.getByTestId('scenario-open').first().click();
    assert(await page.locator('#scenario-snapshot-notice').isVisible(), 'Opened snapshot has no archive notice');
    await page.getByTestId('scenario-delete').first().click();
    await page.keyboard.press('Escape');
    assert(await page.getByTestId('scenario-card').count() === 2, 'Escape deleted scenario');
    await page.getByTestId('scenario-delete').first().click();
    await page.locator('#scenario-delete-confirm').click();
    await page.waitForFunction(() => document.querySelectorAll('[data-testid="scenario-card"]').length === 1);
    assert(await page.evaluate(() => document.activeElement?.closest('[data-testid="scenario-card"]') !== null), 'Focus lost after deletion');
    for (const width of [360, 390, 768]) {
      await page.setViewportSize({ width, height: 900 });
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Horizontal page overflow at ${width}px`);
    }
    await page.setViewportSize({ width: 390, height: 900 });
    await page.locator('#scenarios-section').screenshot({ path: 'tests/artifacts/scenarios/ui-mobile.png' });
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal page overflow at 200% text');
    await page.evaluate(() => { document.documentElement.style.fontSize = ''; });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#scenarios-section').screenshot({ path: 'tests/artifacts/scenarios/ui-desktop.png' });
    const qualityCases = await page.evaluate(async () => {
      const { qualitySummary } = await import('/static/js/data-quality.js');
      const now = Date.now(), data = { source: 'cache', data_quality: { version:1, completeness: { status: 'usable_for_model', reasons: [{ code: 'osm', text: 'Проверить OSM' }] } }, data_meta: { houses: { fetched_at: (now - 8 * 86400000) / 1000 }, competitors: { fetched_at: now / 1000 } } };
      const stale = qualitySummary(data, now), fresh = qualitySummary({ ...data, data_meta: { houses: { fetched_at: now / 1000 }, competitors: { fetched_at: now / 1000 } } }, now);
      const unknown = qualitySummary({ ...data, data_meta: { houses: { fetched_at: now / 1000 } } }, now), legacy = qualitySummary({ ...data, data_quality: undefined }, now), demo = qualitySummary({ ...data, source: 'demo' }, now);
      return { stale, fresh, unknown, legacy, demo };
    });
    assert(qualityCases.stale.freshness === 'Старше 7 дней' && qualityCases.fresh.freshness === 'За последние 24 часа', 'Archive age is not recomputed');
    assert(qualityCases.unknown.freshness === 'Свежесть неизвестна' && qualityCases.legacy.completeness === 'Не оценено' && qualityCases.demo.freshness === 'Демонстрационные данные', 'Missing/legacy/demo quality is misleading');
    assert(qualityCases.stale.dates.length === 2 && qualityCases.stale.reasons.includes('Проверить OSM'), 'Quality metadata/reasons missing');
    const preserved = await page.evaluate(() => localStorage.getItem('geomarketing.scenarios.v1'));
    await page.evaluate(() => { Storage.prototype.setItem = function () { throw new DOMException('Quota', 'QuotaExceededError'); }; });
    await page.getByTestId('scenario-duplicate').click();
    await page.waitForFunction(() => document.querySelector('#scenario-status').textContent.includes('переполнено'));
    assert(await page.evaluate(() => localStorage.getItem('geomarketing.scenarios.v1')) === preserved, 'Quota failure destroyed saved scenarios');
    await page.reload();
    await page.evaluate(() => localStorage.setItem('geomarketing.scenarios.v1', '{damaged'));
    await page.reload();
    await page.locator('#scenario-download-raw').waitFor({ state: 'visible' });
    assert(await page.locator('#scenario-save').isDisabled(), 'Damaged storage accepts writes');
    await page.locator('#scenario-reset').click();
    await page.keyboard.press('Escape');
    assert(await page.evaluate(() => localStorage.getItem('geomarketing.scenarios.v1')) === '{damaged', 'Escape cleared damaged storage');
    await page.locator('#scenario-reset').click();
    await page.locator('#scenario-reset-confirm').click();
    await page.waitForFunction(() => localStorage.getItem('geomarketing.scenarios.v1') === null);
    await page.evaluate(raw => localStorage.setItem('geomarketing.scenarios.v1', raw), preserved);
    await page.reload();
    await page.evaluate(() => Object.defineProperty(navigator, 'locks', { configurable: true, value: undefined }));
    await page.evaluate(async () => { const { updateScenarioAvailability } = await import('/static/js/scenarios.js'); updateScenarioAvailability(); });
    assert(await page.locator('#scenario-save').isDisabled() && await page.getByTestId('scenario-delete').isDisabled() && await page.locator('#scenario-export').isEnabled(), 'No-lock mode is not read-only');
    assert(errors.length === 0, errors.join('\n'));
    return { passed: ['save', 'text safety', 'reload', 'duplicate', 'edit', 'compare exactly two', 'CSV', 'print contexts', 'open archive', 'Escape', 'delete focus', 'mobile', 'reduced motion', 'archive quality', 'quota preservation', 'damaged reset confirmation', 'read-only without Web Locks'], pageErrors: errors };
  } finally { await context.close(); }
}
